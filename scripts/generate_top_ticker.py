"""Generate the fixed Chinese banner ROM and an independent raster fixture."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TEXT = "本项目是安路科技赛道一项目，内容为校园交互终端演示，课件仅作演示使用，实际应用场景可更换调整"
FONT = "C:/Windows/Fonts/simsun.ttc"
assert len(TEXT) <= 56  # At least eight full-width spaces before repeating.
canvas = Image.new("1", (1024, 16))
draw = ImageDraw.Draw(canvas)
font = ImageFont.truetype(FONT, 16)
for i, char in enumerate(TEXT):
    draw.text((i * 16, -font.getbbox("本")[1]), char, font=font, fill=1)
columns = [sum(canvas.getpixel((x, y)) << y for y in range(16)) for x in range(1024)]
template = '''// Generated by scripts/generate_top_ticker.py. Fixed 64-cell Chinese banner.
// Two-cycle look-ahead matches the physical-coordinate overlay pipeline.
module dmz_top_ticker(input clk,reset,frame_tick,
 input [10:0] x,input [9:0] y,output reg ink,shade);
reg [9:0] scroll;
reg half_frame;
always @(posedge clk)begin
 if(reset)begin scroll<=0;half_frame<=0;end
 else if(frame_tick)begin
  half_frame<=~half_frame;
  if(half_frame)scroll<=scroll+1'b1;
 end
end
wire [10:0] ahead_x=x>=1648?x-11'd1648:x+11'd2;
wire [9:0] ahead_y=x>=1648?(y==749?10'd0:y+1'b1):y;
wire [9:0] address=ahead_x[10:1]+scroll;
reg [15:0] font_rom[0:1023]; /* fehdl force_ram=1, ram_style="bram" */
initial begin
@ROM@
end
reg [15:0] column;
reg [3:0] row_q;
reg inside_q,text_q;
always @(posedge clk)column<=font_rom[address];
always @(posedge clk)begin
 if(reset)begin row_q<=0;inside_q<=0;text_q<=0;ink<=0;shade<=0;end
 else begin
  row_q<=4'((ahead_y-10'd4)>>1);
  inside_q<=ahead_x<1280&&ahead_y<40;
  text_q<=ahead_y>=4&&ahead_y<36;
  ink<=inside_q&&text_q&&column[row_q];
  shade<=inside_q;
 end
end
endmodule
'''
rom = "\n".join(f" font_rom[{i}]=16'h{value:04x};" for i, value in enumerate(columns))
(ROOT / "rtl/system/dmz_top_ticker.sv").write_text(template.replace("@ROM@", rom), encoding="utf-8")
(ROOT / "sim/system/top_ticker_columns.hex").write_text("\n".join(f"{v:04x}" for v in columns) + "\n", encoding="ascii")
preview = Image.new("RGB", (2048, 40), "#08182c")
preview.paste("white", (0, 4), canvas.resize((2048, 32), Image.Resampling.NEAREST))
preview.save(ROOT / "docs/top_ticker_strip.png")
print(f"Generated {len(TEXT)} characters + {64-len(TEXT)} full-width spaces; 2048 physical pixels per loop")
